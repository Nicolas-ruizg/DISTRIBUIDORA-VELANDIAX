-- Deposito por producto y tipo de envio en pedidos.

ALTER TABLE PRODUCTO
    ADD COLUMN IF NOT EXISTS ID_DEPOSITO VARCHAR(20);

UPDATE PRODUCTO
SET ID_DEPOSITO = 'DEP001'
WHERE ID_DEPOSITO IS NULL OR BTRIM(ID_DEPOSITO) = '';

ALTER TABLE PRODUCTO
    ALTER COLUMN ID_DEPOSITO SET NOT NULL,
    ALTER COLUMN ID_DEPOSITO SET DEFAULT 'DEP001';

ALTER TABLE PRODUCTO
    DROP CONSTRAINT IF EXISTS FK_PRODUCTO_DEPOSITO,
    ADD CONSTRAINT FK_PRODUCTO_DEPOSITO
    FOREIGN KEY (ID_DEPOSITO)
    REFERENCES DEPOSITOS(ID_DEPOSITO);

CREATE INDEX IF NOT EXISTS IDX_PRODUCTO_DEPOSITO
ON PRODUCTO(ID_DEPOSITO);

ALTER TABLE PEDIDO
    ADD COLUMN IF NOT EXISTS TIPO_ENVIO VARCHAR(30);

UPDATE PEDIDO
SET TIPO_ENVIO = 'CONTRAENTREGA'
WHERE CANAL_VENTA = 'WEB'
  AND ESTADO_PAGO IN ('PAGO_50', 'PAGO_TOTAL')
  AND TIPO_ENVIO IS NULL;

UPDATE PEDIDO
SET TIPO_ENVIO = NULL
WHERE CANAL_VENTA = 'PRESENCIAL';

UPDATE PEDIDO
SET PRECIO_ENVIO = 0
WHERE CANAL_VENTA = 'PRESENCIAL';

ALTER TABLE PEDIDO
    DROP CONSTRAINT IF EXISTS CK_PEDIDO_TIPO_ENVIO,
    ADD CONSTRAINT CK_PEDIDO_TIPO_ENVIO
    CHECK (TIPO_ENVIO IS NULL OR TIPO_ENVIO IN ('CONTRAENTREGA', 'GRATIS'));
