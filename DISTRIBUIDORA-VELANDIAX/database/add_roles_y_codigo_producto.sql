-- Ejecutar sobre bases existentes antes de usar la nueva version del backend.

ALTER TABLE USUARIOS
    DROP CONSTRAINT IF EXISTS CK_USUARIOS_ROL;

ALTER TABLE USUARIOS
    ADD CONSTRAINT CK_USUARIOS_ROL
    CHECK (ROL IN ('ADMINISTRADOR', 'VENDEDOR', 'INVENTARIO'));

ALTER TABLE PRODUCTO
    ADD COLUMN IF NOT EXISTS CODIGO_PRODUCTO VARCHAR(60);

UPDATE PRODUCTO
SET CODIGO_PRODUCTO = 'VX-' || LPAD(ID_PRODUCTO::TEXT, 4, '0')
WHERE CODIGO_PRODUCTO IS NULL OR BTRIM(CODIGO_PRODUCTO) = '';

ALTER TABLE PRODUCTO
    ALTER COLUMN CODIGO_PRODUCTO SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS UX_PRODUCTO_CODIGO_PRODUCTO
ON PRODUCTO(CODIGO_PRODUCTO);

CREATE INDEX IF NOT EXISTS IDX_PRODUCTO_CODIGO
ON PRODUCTO(CODIGO_PRODUCTO);
