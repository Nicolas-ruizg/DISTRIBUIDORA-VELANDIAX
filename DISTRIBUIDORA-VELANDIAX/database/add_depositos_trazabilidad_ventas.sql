-- Depositos, trazabilidad de venta y datos de cliente.

CREATE TABLE IF NOT EXISTS DEPOSITOS (
    ID_DEPOSITO VARCHAR(20) NOT NULL,
    NOMBRE VARCHAR(120),
    ACTIVO BOOLEAN NOT NULL DEFAULT TRUE,
    FECHA_CREACION TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_DEPOSITOS
        PRIMARY KEY (ID_DEPOSITO)
);

INSERT INTO DEPOSITOS (ID_DEPOSITO, NOMBRE)
VALUES
    ('DEP001', 'Deposito 1'),
    ('DEP002', 'Deposito 2')
ON CONFLICT (ID_DEPOSITO) DO NOTHING;

ALTER TABLE USUARIOS
    ADD COLUMN IF NOT EXISTS CODIGO_CUENTA VARCHAR(20);

UPDATE USUARIOS
SET CODIGO_CUENTA = CASE
    WHEN ROL = 'VENDEDOR' THEN 'VEND001'
    WHEN ROL = 'INVENTARIO' THEN 'INV001'
    WHEN ROL = 'ADMINISTRADOR' THEN 'ADMIN001'
    ELSE 'USR' || LPAD(ID_USUARIO::TEXT, 3, '0')
END
WHERE CODIGO_CUENTA IS NULL OR BTRIM(CODIGO_CUENTA) = '';

CREATE UNIQUE INDEX IF NOT EXISTS UX_USUARIOS_CODIGO_CUENTA
ON USUARIOS(CODIGO_CUENTA)
WHERE CODIGO_CUENTA IS NOT NULL;

ALTER TABLE CLIENTES
    ADD COLUMN IF NOT EXISTS CEDULA VARCHAR(30);

CREATE UNIQUE INDEX IF NOT EXISTS UX_CLIENTES_CEDULA
ON CLIENTES(CEDULA)
WHERE CEDULA IS NOT NULL;

ALTER TABLE PEDIDO
    ADD COLUMN IF NOT EXISTS ID_DEPOSITO VARCHAR(20),
    ADD COLUMN IF NOT EXISTS ID_USUARIO_VENTA INTEGER,
    ADD COLUMN IF NOT EXISTS ID_USUARIO_INVENTARIO INTEGER,
    ADD COLUMN IF NOT EXISTS CANAL_VENTA VARCHAR(20);

UPDATE PEDIDO
SET ID_DEPOSITO = 'DEP001'
WHERE ID_DEPOSITO IS NULL OR BTRIM(ID_DEPOSITO) = '';

UPDATE PEDIDO
SET CANAL_VENTA = 'WEB'
WHERE CANAL_VENTA IS NULL OR BTRIM(CANAL_VENTA) = '';

ALTER TABLE PEDIDO
    ALTER COLUMN ID_DEPOSITO SET NOT NULL,
    ALTER COLUMN ID_DEPOSITO SET DEFAULT 'DEP001',
    ALTER COLUMN CANAL_VENTA SET NOT NULL,
    ALTER COLUMN CANAL_VENTA SET DEFAULT 'WEB';

ALTER TABLE PEDIDO
    DROP CONSTRAINT IF EXISTS FK_PEDIDO_DEPOSITO,
    ADD CONSTRAINT FK_PEDIDO_DEPOSITO
    FOREIGN KEY (ID_DEPOSITO)
    REFERENCES DEPOSITOS(ID_DEPOSITO);

ALTER TABLE PEDIDO
    DROP CONSTRAINT IF EXISTS FK_PEDIDO_USUARIO_VENTA,
    ADD CONSTRAINT FK_PEDIDO_USUARIO_VENTA
    FOREIGN KEY (ID_USUARIO_VENTA)
    REFERENCES USUARIOS(ID_USUARIO);

ALTER TABLE PEDIDO
    DROP CONSTRAINT IF EXISTS FK_PEDIDO_USUARIO_INVENTARIO,
    ADD CONSTRAINT FK_PEDIDO_USUARIO_INVENTARIO
    FOREIGN KEY (ID_USUARIO_INVENTARIO)
    REFERENCES USUARIOS(ID_USUARIO);

ALTER TABLE PEDIDO
    DROP CONSTRAINT IF EXISTS CK_PEDIDO_CANAL_VENTA,
    ADD CONSTRAINT CK_PEDIDO_CANAL_VENTA
    CHECK (CANAL_VENTA IN ('PRESENCIAL', 'WEB'));

CREATE INDEX IF NOT EXISTS IDX_PEDIDO_DEPOSITO
ON PEDIDO(ID_DEPOSITO);

CREATE INDEX IF NOT EXISTS IDX_PEDIDO_USUARIO_VENTA
ON PEDIDO(ID_USUARIO_VENTA);

CREATE INDEX IF NOT EXISTS IDX_PEDIDO_FECHA
ON PEDIDO(FECHA);
