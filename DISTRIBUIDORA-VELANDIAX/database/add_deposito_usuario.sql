-- Relaciona usuarios con depositos para limitar visibilidad operativa.

ALTER TABLE USUARIOS
    ADD COLUMN IF NOT EXISTS ID_DEPOSITO VARCHAR(20);

UPDATE USUARIOS
SET ID_DEPOSITO = 'DEP001'
WHERE ID_DEPOSITO IS NULL
  AND ROL IN ('VENDEDOR', 'INVENTARIO');

ALTER TABLE USUARIOS
    DROP CONSTRAINT IF EXISTS FK_USUARIOS_DEPOSITO,
    ADD CONSTRAINT FK_USUARIOS_DEPOSITO
    FOREIGN KEY (ID_DEPOSITO)
    REFERENCES DEPOSITOS(ID_DEPOSITO);

CREATE INDEX IF NOT EXISTS IDX_USUARIOS_DEPOSITO
ON USUARIOS(ID_DEPOSITO);
